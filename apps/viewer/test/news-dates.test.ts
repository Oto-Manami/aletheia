// ニュースの題名・本文から日付を拾う規則（設計書 決定記録 0030）。題名・番組はすべて架空
import { describe, expect, it } from "vitest";
import { newsDates } from "../src/source/news-dates.ts";

describe("ニュースに出てくる日付を拾う", () => {
  it("題名と本文の日付を、重なりなく出てくる順に拾う", () => {
    expect(
      newsDates({
        title: "11月8日(日)7:30〜試験テレビ「試験の番組」に試験 花子が出演！",
        body: "11月8日(日)7:30〜試験テレビ「試験の番組」に試験花子が出演いたします！",
        publishedDate: "2026-11-05",
      }),
    ).toEqual(["2026-11-08"]);
  });

  it("年の書いていない日付が大きく前の月なら翌年とみなす", () => {
    expect(
      newsDates({
        title: "試験のツアーの追加公演が決定",
        body: "1月10日(土)と2026年1月11日(日)、さらに 1月12日 にも追加公演を行います。",
        publishedDate: "2025-12-20",
      }),
    ).toEqual(["2026-01-10", "2026-01-11", "2026-01-12"]);
  });

  it("日付が無ければ空にする", () => {
    expect(
      newsDates({
        title: "新しいシングルの発売が決定",
        body: "詳しくは後日お知らせします。",
        publishedDate: "2026-10-28",
      }),
    ).toEqual([]);
  });

  it("「本日」が日付より前にあれば、ニュースの日付を先に入れる", () => {
    expect(
      newsDates({
        title: "試験グループ 2 期生の発表がスタート！",
        body: "本日より、2 期生の発表がスタートいたしました！ 3月12日(水)以降も、毎日 1 名ずつ発表します。",
        publishedDate: "2025-03-11",
      }),
    ).toEqual(["2025-03-11", "2025-03-12"]);
  });
});
